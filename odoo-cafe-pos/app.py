def login_required(f):
    @wraps(f)
    def decorated(*args, **kwargs):
        if 'user_id' not in session:
            return jsonify({'error': 'Authentication required'}), 401
        return f(*args, **kwargs)
    return decorated


def role_required(*roles):
    def wrapper(f):
        @wraps(f)
        def decorated(*args, **kwargs):
            if 'user_id' not in session:
                return jsonify({'error': 'Authentication required'}), 401
            if session.get('role') not in roles:
                return jsonify({'error': 'Insufficient permissions'}), 403
            return f(*args, **kwargs)
        return decorated
    return wrapper


def generate_order_number():
    return 'ORD-' + datetime.utcnow().strftime('%y%m%d') + '-' + ''.join(random.choices(string.digits, k=4))


def generate_qr_payload(text):
    """Returns a URL to a QR code image generated by an external free API (no API key)."""
    import urllib.parse
    encoded = urllib.parse.quote(text)
    return f"https://api.qrserver.com/v1/create-qr-code/?size=220x220&data={encoded}"


