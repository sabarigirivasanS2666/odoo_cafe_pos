def recalc_order_totals(order, discount_value=0.0, discount_type='fixed'):
    subtotal = sum(item.price * item.quantity for item in order.items)
    tax_amount = sum((item.price * item.quantity) * (item.tax / 100.0) for item in order.items)

    if discount_type == 'percentage':
        discount = subtotal * (discount_value / 100.0)
    else:
        discount = discount_value

    grand_total = max(subtotal + tax_amount - discount, 0)
    order.subtotal = round(subtotal, 2)
    order.tax_amount = round(tax_amount, 2)
    order.discount = round(discount, 2)
    order.grand_total = round(grand_total, 2)


def points_value(points):
    """₹ value of a number of loyalty points."""
    return round(points * POINTS_REDEEM_VALUE, 2)


def apply_points_redemption(order, customer, requested_points=None):
    """Auto-applies a customer's available loyalty points as an extra discount on
    top of subtotal+tax-discount, capped so the order total never goes below 0 and
    never redeems more points than the customer actually has. Deducts the points
    from the customer's balance and writes a ledger entry, but does not commit —
    caller is expected to commit alongside the rest of the order changes.
    Returns (points_redeemed, points_discount_value)."""
    if not customer or customer.loyalty_points <= 0:
        return 0, 0.0

    available_points = customer.loyalty_points
    if requested_points is not None:
        available_points = min(available_points, max(0, int(requested_points)))

    # Don't let points discount drive the total below zero.
    remaining_payable = max(order.subtotal + order.tax_amount - order.discount, 0)
    max_points_usable = int(remaining_payable / POINTS_REDEEM_VALUE)
    points_to_redeem = min(available_points, max_points_usable)

    if points_to_redeem <= 0:
        return 0, 0.0

    discount_from_points = points_value(points_to_redeem)
    order.points_redeemed = points_to_redeem
    order.points_discount = discount_from_points
    order.discount = round(order.discount + discount_from_points, 2)
    order.grand_total = max(round(order.subtotal + order.tax_amount - order.discount, 2), 0)

    customer.loyalty_points -= points_to_redeem
    db.session.add(PointsLedger(
        customer_id=customer.id, order_id=order.id,
        change=-points_to_redeem, reason='redeemed',
        balance_after=customer.loyalty_points
    ))
    return points_to_redeem, discount_from_points


def award_points_for_order(order, customer):
    """Credits loyalty points for a paid order (1 point per ₹{POINTS_EARN_RATE} spent
    on the final grand_total). Writes a ledger entry. Does not commit."""
    if not customer:
        return 0
    earned = int(order.grand_total // POINTS_EARN_RATE)
    if earned <= 0:
        order.points_earned = 0
        return 0
    customer.loyalty_points += earned
    order.points_earned = earned
    db.session.add(PointsLedger(
        customer_id=customer.id, order_id=order.id,
        change=earned, reason='earned',
        balance_after=customer.loyalty_points
    ))
    return earned


