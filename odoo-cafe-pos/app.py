@app.route('/api/customer/me', methods=['GET'])
@role_required('customer')
def customer_me():
    user = User.query.get(session['user_id'])
    customer = get_or_create_customer_for_user(user)
    db.session.commit()

    orders = Order.query.filter_by(customer_id=customer.id).order_by(Order.created_at.desc()).all()
    total_orders = len(orders)
    total_spent = sum(o.grand_total for o in orders if o.payment_status == 'paid')
    pending_orders = len([o for o in orders if o.status != 'completed'])

    return jsonify({
        'user': user.to_dict(),
        'customer': customer.to_dict(),
        'stats': {
            'total_orders': total_orders,
            'total_spent': round(total_spent, 2),
            'pending_orders': pending_orders,
            'loyalty_points': customer.loyalty_points,
            'points_value': points_value(customer.loyalty_points)
        },
        'recent_orders': [o.to_dict() for o in orders[:5]]
    })


