@app.route('/api/coupons/validate/<code>', methods=['GET'])
def validate_coupon(code):
    coupon = Coupon.query.filter_by(code=code.upper(), active=True).first()
    if not coupon:
        return jsonify({'valid': False, 'error': 'Invalid or expired coupon'}), 404
    if coupon.is_expired():
        expired_on = coupon.expiry_date.strftime('%d %b %Y')
        return jsonify({'valid': False, 'error': f'This coupon expired on {expired_on}'}), 404
    return jsonify({'valid': True, 'coupon': coupon.to_dict()})


