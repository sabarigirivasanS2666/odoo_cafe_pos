@app.route('/api/orders/<int:order_id>/pay', methods=['POST'])
def pay_order(order_id):
    order = Order.query.get_or_404(order_id)
    data = request.get_json()
    method = data.get('method', 'cash')

    if method not in ('cash', 'card', 'upi'):
        return jsonify({'error': 'Invalid payment method'}), 400

    payment = Payment(
        order_id=order.id,
        method=method,
        amount=order.grand_total,
        status='success',
        transaction_ref='TXN' + ''.join(random.choices(string.ascii_uppercase + string.digits, k=10))
    )
    db.session.add(payment)
    order.payment_status = 'paid'

    points_earned = 0
    if order.customer_id:
        customer = Customer.query.get(order.customer_id)
        points_earned = award_points_for_order(order, customer)

    if order.table_id:
        table = Table.query.get(order.table_id)
        if table:
            table.status = 'available'

    db.session.commit()

    response = {'order': order.to_dict(), 'payment': payment.to_dict(), 'points_earned': points_earned}
    if method == 'upi':
        upi_string = f"upi://pay?pa=odoocafe@upi&pn=OdooCafePOS&am={order.grand_total}&cu=INR&tn={order.order_number}"
        response['upi_qr'] = generate_qr_payload(upi_string)
    return jsonify(response), 200


