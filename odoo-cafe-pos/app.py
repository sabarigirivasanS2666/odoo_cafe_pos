@app.route('/api/reports/summary', methods=['GET'])
def reports_summary():
    orders = Order.query.filter_by(payment_status='paid').all()
    total_orders = len(orders)
    total_revenue = sum(o.grand_total for o in orders)
    avg_order_value = round(total_revenue / total_orders, 2) if total_orders else 0

    product_totals = {}
    category_totals = {}
    for order in orders:
        for item in order.items:
            product_totals[item.product_name] = product_totals.get(item.product_name, 0) + item.quantity
            product = Product.query.get(item.product_id)
            if product and product.category:
                cname = product.category.name
                category_totals[cname] = category_totals.get(cname, 0) + item.subtotal

    top_products = sorted(product_totals.items(), key=lambda x: x[1], reverse=True)[:5]
    top_categories = sorted(category_totals.items(), key=lambda x: x[1], reverse=True)[:5]

    monthly_sales = {}
    for order in orders:
        month_key = order.created_at.strftime('%Y-%m')
        monthly_sales[month_key] = monthly_sales.get(month_key, 0) + order.grand_total
    monthly_sales_sorted = sorted(monthly_sales.items())

    return jsonify({
        'total_orders': total_orders,
        'total_revenue': round(total_revenue, 2),
        'avg_order_value': avg_order_value,
        'top_products': [{'name': k, 'quantity': v} for k, v in top_products],
        'top_categories': [{'name': k, 'revenue': round(v, 2)} for k, v in top_categories],
        'monthly_sales': [{'month': k, 'revenue': round(v, 2)} for k, v in monthly_sales_sorted]
    })


