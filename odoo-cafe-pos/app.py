@app.route('/api/orders', methods=['POST'])
def create_order():
    data = request.get_json()
    items_data = data.get('items', [])
    if not items_data:
        return jsonify({'error': 'Order must contain at least one item'}), 400

    order_type = data.get('order_type', 'pos')
    # Choosing a table is compulsory for orders placed from the POS cart.
    if order_type == 'pos' and not data.get('table_id'):
        return jsonify({'error': 'Please select a table before sending the order'}), 400

    customer_id = data.get('customer_id')
    if not customer_id and session.get('role') == 'customer' and 'user_id' in session:
        user = User.query.get(session['user_id'])
        if user:
            customer_id = get_or_create_customer_for_user(user).id

    order = Order(
        order_number=generate_order_number(),
        table_id=data.get('table_id'),
        customer_id=customer_id,
        order_type=order_type,
        status='to_cook',
        coupon_code=data.get('coupon_code')
    )
    db.session.add(order)
    db.session.flush()

    for item in items_data:
        product = Product.query.get(item['product_id'])
        if not product:
            continue
        qty = int(item.get('quantity', 1))
        order_item = OrderItem(
            order_id=order.id,
            product_id=product.id,
            product_name=product.name,
            quantity=qty,
            price=product.price,
            tax=product.tax,
            subtotal=round(product.price * qty, 2)
        )
        db.session.add(order_item)

    db.session.flush()
    db.session.refresh(order)

    discount_value = float(data.get('discount_value', 0))
    discount_type = data.get('discount_type', 'fixed')

    if order.coupon_code:
        coupon = Coupon.query.filter_by(code=order.coupon_code.upper(), active=True).first()
        if coupon and not coupon.is_expired():
            discount_value = coupon.discount_value
            discount_type = coupon.discount_type
        else:
            # Coupon is invalid or has passed its 5-day expiry — don't apply its discount.
            order.coupon_code = None

    recalc_order_totals(order, discount_value, discount_type)

    # Auto-apply the logged-in customer's loyalty points as an extra discount,
    # on top of any coupon, unless the client explicitly opts out.
    use_points = data.get('use_points', True)
    customer = Customer.query.get(customer_id) if customer_id else None
    if use_points and customer:
        apply_points_redemption(order, customer, data.get('points_to_redeem'))

    if order.table_id:
        table = Table.query.get(order.table_id)
        if table:
            table.status = 'occupied'

    db.session.commit()
    return jsonify(order.to_dict()), 201


