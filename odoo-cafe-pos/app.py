@app.route('/api/floors/<int:floor_id>/duplicate', methods=['POST'])
@role_required('admin', 'employee')
def duplicate_floor(floor_id):
    """Clones a floor plus every table on it onto a brand-new floor, so a whole
    seating layout can be replicated in one click instead of recreating each
    table by hand."""
    floor = Floor.query.get_or_404(floor_id)

    new_floor = Floor(name=f'{floor.name} (Copy)')
    db.session.add(new_floor)
    db.session.flush()

    next_number = (db.session.query(db.func.max(Table.number)).scalar() or 0) + 1
    for t in floor.tables:
        new_table = Table(
            number=next_number,
            floor_id=new_floor.id,
            seats=t.seats,
            status='available'
        )
        db.session.add(new_table)
        db.session.flush()
        new_table.qr_code = generate_qr_payload(request.host_url.rstrip('/') + f'/self-order/{new_table.id}')
        next_number += 1

    db.session.commit()
    result = new_floor.to_dict()
    result['tables'] = [t.to_dict() for t in new_floor.tables]
    return jsonify(result), 201


